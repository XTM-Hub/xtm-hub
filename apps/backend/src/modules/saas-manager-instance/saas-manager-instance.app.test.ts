import { readFileSync } from 'node:fs';
import { v4 as uuidv4 } from 'uuid';
import {
  afterAll,
  afterEach,
  beforeAll,
  describe,
  expect,
  it,
  vi,
} from 'vitest';
import { TestHelper } from '../../../tests/helper/test.helper';
import {
  SaasProduct,
  type SaasManagerInstanceInput,
} from '../../__generated__/resolvers-types';
import { logApp } from '../../utils/app-logger.util';
import { BadRequestErrorCode } from '../../utils/error/error.code';
import {
  MAX_INSTANCES_PER_PUSH,
  SaasManagerInstanceApp,
} from './saas-manager-instance.app';
import { IN_SERVICE_STATUS_FAMILY } from './saas-manager-instance.schema';

// Generated by SaaS Manager's test suite (test_contract_fixture): the instances it pushes.
interface SaasManagerContract {
  generated_at: string;
  instances: SaasManagerInstanceInput[];
}

const CONTRACT = JSON.parse(
  readFileSync(
    new URL(
      '../../../tests/fixtures/saas-manager-contract.json',
      import.meta.url
    ),
    'utf8'
  )
) as SaasManagerContract;

const OLDER = '2026-01-01T00:00:00.000Z';
const NEWER = '2026-01-02T00:00:00.000Z';
const MINUTE_MS = 60 * 1000;
const inMinutes = (minutes: number) =>
  new Date(Date.now() + minutes * MINUTE_MS).toISOString();
const CUSTOMER_NAME = 'test-customer';
const CUSTOMER = 'cust-test';
const PLAN_CODE = 'test-plan';
const STATUS = 'DEPLOYED';
const WINDOW_START = '2026-01-01T00:00:00+00:00';
const WINDOW_END = '2026-01-02T00:00:00+00:00';
// A product SaaS Manager sells that the Hub does not know.
const UNKNOWN_PRODUCT = 'OCRQ';

// The data SaaS Manager sends for an instance, with the fields the Hub requires.
const makeData = (id: string, data: Record<string, unknown> = {}) => ({
  id,
  plan: PLAN_CODE,
  status: STATUS,
  customer: CUSTOMER,
  ...data,
});

const makeInstance = ({
  id,
  data = {},
  metrics,
  customerName = CUSTOMER_NAME,
  statusFamily = IN_SERVICE_STATUS_FAMILY,
}: {
  id: string;
  data?: Record<string, unknown>;
  metrics?: Record<string, unknown> | null;
  customerName?: string;
  statusFamily?: string;
}): SaasManagerInstanceInput => ({
  data: makeData(id, data),
  index: {
    customer_name: customerName,
    status_family: statusFamily,
  },
  metrics,
});

// An instance whose data lacks the key.
const makeInstanceWithout = (
  id: string,
  key: string
): SaasManagerInstanceInput => ({
  ...makeInstance({ id }),
  data: Object.fromEntries(
    Object.entries(makeData(id)).filter(([name]) => name !== key)
  ),
});

// A window of metrics as the instance detail charts it.
const makeWindow = (resolution = 'day') => ({
  start: WINDOW_START,
  end: WINDOW_END,
  resolution,
  series: [],
});

describe('saas manager instance app', () => {
  describe('the contract recorded by SaaS Manager', () => {
    const contractIds = CONTRACT.instances.map(
      ({ data }) => (data as { id: string }).id
    );

    beforeAll(async () => {
      await SaasManagerInstanceApp.upsertInstances({
        generatedAt: CONTRACT.generated_at,
        instances: CONTRACT.instances,
      });
    });

    afterAll(async () => {
      await TestHelper.saasManagerInstance.delete(contractIds);
    });

    it('should store every instance SaaS Manager pushes, with its data and its metrics', async () => {
      // When
      const stored = await Promise.all(
        contractIds.map((id) => TestHelper.saasManagerInstance.load(id))
      );

      // Then
      expect(
        stored.map((instance) => ({
          data: instance?.data,
          metrics: instance?.metrics,
        }))
      ).toEqual(
        CONTRACT.instances.map(({ data, metrics }) => ({
          data,
          metrics: metrics ?? null,
        }))
      );
    });
  });

  describe('upsertInstances', () => {
    let ids: string[] = [];

    afterEach(async () => {
      vi.restoreAllMocks();
      await TestHelper.saasManagerInstance.delete(ids);
      ids = [];
    });

    const newId = () => {
      const id = uuidv4();
      ids.push(id);
      return id;
    };

    it.each([
      ['an older copy', OLDER, NEWER, 'second', { applied: 1, skipped: 0 }],
      [
        'a copy generated at the same time',
        NEWER,
        NEWER,
        'second',
        { applied: 1, skipped: 0 },
      ],
      ['a newer copy', NEWER, OLDER, 'first', { applied: 0, skipped: 1 }],
    ])(
      'should keep the copy generated last when the Hub stores %s',
      async (
        _,
        firstGeneratedAt,
        secondGeneratedAt,
        expectedHostname,
        counts
      ) => {
        // Given
        const id = newId();
        await SaasManagerInstanceApp.upsertInstances({
          generatedAt: firstGeneratedAt,
          instances: [makeInstance({ id, data: { hostname: 'first' } })],
        });

        // When
        const result = await SaasManagerInstanceApp.upsertInstances({
          generatedAt: secondGeneratedAt,
          instances: [makeInstance({ id, data: { hostname: 'second' } })],
        });

        // Then
        expect({
          result,
          stored: (await TestHelper.saasManagerInstance.load(id))?.data,
        }).toEqual({
          result: { ...counts, removed: 0 },
          stored: makeData(id, { hostname: expectedHostname }),
        });
      }
    );

    it('should keep the stored metrics when the instance is sent without metrics', async () => {
      // Given
      const id = newId();
      const metrics = { '32': makeWindow() };
      await SaasManagerInstanceApp.upsertInstances({
        generatedAt: OLDER,
        instances: [makeInstance({ id, metrics })],
      });

      // When
      await SaasManagerInstanceApp.upsertInstances({
        generatedAt: NEWER,
        instances: [makeInstance({ id, data: { hostname: 'renamed' } })],
      });

      // Then
      const stored = await TestHelper.saasManagerInstance.load(id);
      expect({ data: stored?.data, metrics: stored?.metrics }).toEqual({
        data: makeData(id, { hostname: 'renamed' }),
        metrics,
      });
    });

    it('should replace the stored metrics when the instance is sent with metrics', async () => {
      // Given
      const id = newId();
      await SaasManagerInstanceApp.upsertInstances({
        generatedAt: OLDER,
        instances: [makeInstance({ id, metrics: { '7': makeWindow('hour') } })],
      });

      // When
      await SaasManagerInstanceApp.upsertInstances({
        generatedAt: NEWER,
        instances: [makeInstance({ id, metrics: { '32': makeWindow() } })],
      });

      // Then
      expect((await TestHelper.saasManagerInstance.load(id))?.metrics).toEqual({
        '32': makeWindow(),
      });
    });

    it.each([
      ['an empty hostname', { hostname: '' }, { hostname: null }],
      ['a lower-case product', { product: 'oaev' }, { product: 'OAEV' }],
      [
        // The driver reads a date column as midnight on the Hub clock.
        'an end date with an offset, on its UTC day',
        { end_date: '2027-01-01T23:00:00-05:00' },
        { end_date: new Date(2027, 0, 2) },
      ],
    ])('should store %s as the list serves it', async (_, data, expected) => {
      // Given
      const id = newId();

      // When
      await SaasManagerInstanceApp.upsertInstances({
        generatedAt: NEWER,
        instances: [makeInstance({ id, data })],
      });

      // Then
      expect(await TestHelper.saasManagerInstance.load(id)).toMatchObject(
        expected
      );
    });

    it('should store the plan of the data as the plan name', async () => {
      // Given
      const id = newId();

      // When
      await SaasManagerInstanceApp.upsertInstances({
        generatedAt: NEWER,
        instances: [makeInstance({ id, data: { plan: 'Large' } })],
      });

      // Then
      expect((await TestHelper.saasManagerInstance.load(id))?.plan_name).toBe(
        'Large'
      );
    });

    it('should ignore the plan code SaaS Manager still sends in the index', async () => {
      // Given
      const id = newId();
      const instance = makeInstance({ id, data: { plan: 'Large' } });

      // When
      await SaasManagerInstanceApp.upsertInstances({
        generatedAt: NEWER,
        instances: [
          { ...instance, index: { ...instance.index, plan_code: 'other' } },
        ],
      });

      // Then
      expect((await TestHelper.saasManagerInstance.load(id))?.plan_name).toBe(
        'Large'
      );
    });

    it('should write a push of the maximum size', async () => {
      // Given
      const instances = Array.from({ length: MAX_INSTANCES_PER_PUSH }, () =>
        makeInstance({ id: newId() })
      );

      // When
      const result = await SaasManagerInstanceApp.upsertInstances({
        generatedAt: NEWER,
        instances,
      });

      // Then
      expect(result).toEqual({
        applied: MAX_INSTANCES_PER_PUSH,
        skipped: 0,
        removed: 0,
      });
    });

    it('should refuse a push above the maximum size and write nothing', async () => {
      // Given
      const instances = Array.from({ length: MAX_INSTANCES_PER_PUSH + 1 }, () =>
        makeInstance({ id: newId() })
      );

      // When
      const upsert = SaasManagerInstanceApp.upsertInstances({
        generatedAt: NEWER,
        instances,
      });

      // Then
      await expect(upsert).rejects.toThrow(
        BadRequestErrorCode.InvalidSaasManagerInstance
      );
      expect(await TestHelper.saasManagerInstance.load(ids[0])).toBeUndefined();
    });

    it('should accept a generation date slightly ahead of the Hub clock', async () => {
      // Given
      const id = newId();

      // When
      const result = await SaasManagerInstanceApp.upsertInstances({
        generatedAt: inMinutes(1),
        instances: [makeInstance({ id })],
      });

      // Then
      expect(result).toEqual({
        applied: 1,
        skipped: 0,
        removed: 0,
      });
    });

    it('should write an instance sent twice once, as sent last', async () => {
      // Given
      const id = newId();

      // When
      const result = await SaasManagerInstanceApp.upsertInstances({
        generatedAt: NEWER,
        instances: [
          makeInstance({ id, data: { hostname: 'first' } }),
          makeInstance({ id, data: { hostname: 'last' } }),
        ],
      });

      // Then
      expect({
        result,
        stored: (await TestHelper.saasManagerInstance.load(id))?.data,
      }).toEqual({
        result: { applied: 1, skipped: 1, removed: 0 },
        stored: makeData(id, { hostname: 'last' }),
      });
    });

    it.each([
      ['is not a date', 'yesterday'],
      ['is too far ahead of the Hub clock', inMinutes(60)],
    ])(
      'should refuse the push and write nothing when the generation date %s',
      async (_, generatedAt) => {
        // Given
        const id = newId();

        // When
        const upsert = SaasManagerInstanceApp.upsertInstances({
          generatedAt,
          instances: [makeInstance({ id })],
        });

        // Then
        await expect(upsert).rejects.toThrow(
          BadRequestErrorCode.InvalidSaasManagerInstance
        );
        expect(await TestHelper.saasManagerInstance.load(id)).toBeUndefined();
      }
    );

    // Each case builds the invalid instance from a fresh id, and the id the Hub returns for it.
    it.each<
      [
        string,
        string,
        (id: string) => {
          instance: SaasManagerInstanceInput;
          rejectedId: string | null;
        },
      ]
    >([
      [
        'the data is not an object',
        'data',
        (id) => ({
          instance: { ...makeInstance({ id }), data: ['not', 'an', 'object'] },
          rejectedId: null,
        }),
      ],
      [
        'the id is missing',
        'data.id',
        (id) => ({ instance: makeInstanceWithout(id, 'id'), rejectedId: null }),
      ],
      [
        'the id is not a UUID',
        'data.id',
        (id) => ({
          instance: makeInstance({ id: 'instance-1', data: { hostname: id } }),
          rejectedId: null,
        }),
      ],
      [
        'the plan is missing',
        'data.plan',
        (id) => ({ instance: makeInstanceWithout(id, 'plan'), rejectedId: id }),
      ],
      [
        'the plan is not a string',
        'data.plan',
        (id) => ({
          instance: makeInstance({ id, data: { plan: 3 } }),
          rejectedId: id,
        }),
      ],
      [
        'the status is missing',
        'data.status',
        (id) => ({
          instance: makeInstanceWithout(id, 'status'),
          rejectedId: id,
        }),
      ],
      [
        'the customer is sent as client',
        'data.customer',
        (id) => {
          const instance = makeInstanceWithout(id, 'customer');
          return {
            instance: {
              ...instance,
              data: { ...instance.data, client: CUSTOMER },
            },
            rejectedId: id,
          };
        },
      ],
      [
        'the product is not a string',
        'data.product',
        (id) => ({
          instance: makeInstance({ id, data: { product: 3 } }),
          rejectedId: id,
        }),
      ],
      [
        'the end date is not a date',
        'data.end_date',
        (id) => ({
          instance: makeInstance({ id, data: { end_date: 'soon' } }),
          rejectedId: id,
        }),
      ],
      [
        'the status family is unknown',
        'index.status_family',
        (id) => ({
          instance: makeInstance({ id, statusFamily: '__other_family__' }),
          rejectedId: id,
        }),
      ],
      [
        'the customer name is empty',
        'index.customer_name',
        (id) => ({
          instance: makeInstance({ id, customerName: '' }),
          rejectedId: id,
        }),
      ],
      [
        'the metrics are not an object',
        'metrics',
        (id) => ({
          instance: {
            ...makeInstance({ id }),
            metrics: ['not', 'an', 'object'],
          },
          rejectedId: id,
        }),
      ],
      [
        'a metrics window is neither hourly nor daily',
        'metrics.7.resolution',
        (id) => ({
          instance: makeInstance({ id, metrics: { '7': makeWindow('week') } }),
          rejectedId: id,
        }),
      ],
    ])(
      'should refuse the push, write none of its instances and keep the stored copy when %s',
      async (_, path, makeInvalid) => {
        // Given
        const validId = newId();
        const invalidId = newId();
        await TestHelper.saasManagerInstance.create({
          id: invalidId,
          data: { hostname: 'stored' },
          generated_at: new Date(OLDER),
        });
        const { instance, rejectedId } = makeInvalid(invalidId);
        const logWarn = vi
          .spyOn(logApp, 'warn')
          .mockImplementation(() => undefined);

        // When
        const upsert = SaasManagerInstanceApp.upsertInstances({
          generatedAt: NEWER,
          instances: [makeInstance({ id: validId }), instance],
        });

        // Then
        await expect(upsert).rejects.toThrow(
          BadRequestErrorCode.InvalidSaasManagerInstance
        );
        expect({
          valid: await TestHelper.saasManagerInstance.load(validId),
          stored: (await TestHelper.saasManagerInstance.load(invalidId))?.data,
          log: logWarn.mock.calls,
        }).toEqual({
          valid: undefined,
          stored: { id: invalidId, hostname: 'stored' },
          log: [
            [
              'Refused a SaaS Manager push with invalid instances',
              {
                rejected: [
                  {
                    position: 1,
                    id: rejectedId,
                    reason: expect.stringContaining(`${path}: `),
                  },
                ],
              },
            ],
          ],
        });
      }
    );

    it('should write only the instances of the products the Hub stores, and skip and log the others by product as sent', async () => {
      // Given
      const storedId = newId();
      const ignoredIds = Array.from({ length: 5 }, () => newId());
      const withoutPlan = makeInstanceWithout(ignoredIds[1], 'plan');
      const logInfo = vi
        .spyOn(logApp, 'info')
        .mockImplementation(() => undefined);

      // When
      const result = await SaasManagerInstanceApp.upsertInstances({
        generatedAt: NEWER,
        instances: [
          makeInstance({
            id: ignoredIds[0],
            data: { product: SaasProduct.One },
          }),
          makeInstance({ id: storedId, data: { product: SaasProduct.Octi } }),
          // Ignored before it is validated: the plan it lacks does not refuse the push.
          {
            ...withoutPlan,
            data: {
              ...withoutPlan.data,
              product: SaasProduct.One.toLowerCase(),
            },
          },
          makeInstance({
            id: ignoredIds[2],
            data: { product: UNKNOWN_PRODUCT },
          }),
          makeInstance({
            id: ignoredIds[3],
            data: { product: UNKNOWN_PRODUCT.toLowerCase() },
          }),
          makeInstance({
            id: ignoredIds[4],
            data: { product: UNKNOWN_PRODUCT },
          }),
        ],
      });

      // Then
      expect({
        result,
        stored: (await TestHelper.saasManagerInstance.load(storedId))?.product,
        ignored: await Promise.all(
          ignoredIds.map((id) => TestHelper.saasManagerInstance.load(id))
        ),
        log: logInfo.mock.calls,
      }).toEqual({
        result: { applied: 1, skipped: 5, removed: 0 },
        stored: SaasProduct.Octi,
        ignored: ignoredIds.map(() => undefined),
        log: [
          [
            'Ignored the SaaS Manager instances of products the Hub does not store',
            {
              ignored: {
                [SaasProduct.One]: 1,
                [SaasProduct.One.toLowerCase()]: 1,
                [UNKNOWN_PRODUCT]: 2,
                [UNKNOWN_PRODUCT.toLowerCase()]: 1,
              },
            },
          ],
        ],
      });
    });

    it.each([
      [
        'a field the Hub does not know in the data',
        (id: string) =>
          makeInstance({
            id,
            data: { region: 'eu' },
            metrics: { '7': makeWindow('hour') },
          }),
      ],
      [
        'a metrics window the Hub does not know',
        (id: string) =>
          makeInstance({
            id,
            metrics: { '7': makeWindow('hour'), '365': makeWindow() },
          }),
      ],
      ['no metrics', (id: string) => makeInstance({ id, metrics: null })],
    ])(
      'should store the instance as sent when it carries %s',
      async (_, buildInstance) => {
        // Given
        const id = newId();
        const instance = buildInstance(id);

        // When
        const result = await SaasManagerInstanceApp.upsertInstances({
          generatedAt: NEWER,
          instances: [instance],
        });

        // Then
        const stored = await TestHelper.saasManagerInstance.load(id);
        expect({
          result,
          stored: { data: stored?.data, metrics: stored?.metrics },
        }).toEqual({
          result: { applied: 1, skipped: 0, removed: 0 },
          stored: { data: instance.data, metrics: instance.metrics },
        });
      }
    );
  });

  describe('purgeInstances', () => {
    let ids: string[] = [];

    afterEach(async () => {
      await TestHelper.saasManagerInstance.delete(ids);
      ids = [];
    });

    it('should delete the instances generated before the date and keep the others', async () => {
      // Given
      const olderId = await TestHelper.saasManagerInstance.create({
        generated_at: new Date(OLDER),
      });
      const newerId = await TestHelper.saasManagerInstance.create({
        generated_at: new Date(NEWER),
      });
      ids = [olderId, newerId];

      // When
      const result = await SaasManagerInstanceApp.purgeInstances({
        before: NEWER,
      });

      // Then
      expect({
        result,
        older: await TestHelper.saasManagerInstance.load(olderId),
        newer: (await TestHelper.saasManagerInstance.load(newerId))?.id,
      }).toEqual({
        result: { applied: 0, skipped: 0, removed: 1 },
        older: undefined,
        newer: newerId,
      });
    });

    it.each([
      ['is not a date', 'never'],
      ['is too far ahead of the Hub clock', inMinutes(60)],
    ])('should refuse a date that %s and delete nothing', async (_, before) => {
      // Given
      const id = await TestHelper.saasManagerInstance.create({
        generated_at: new Date(OLDER),
      });
      ids = [id];

      // When
      const purge = SaasManagerInstanceApp.purgeInstances({ before });

      // Then
      await expect(purge).rejects.toThrow(
        BadRequestErrorCode.InvalidSaasManagerInstance
      );
      expect((await TestHelper.saasManagerInstance.load(id))?.id).toBe(id);
    });
  });
});
