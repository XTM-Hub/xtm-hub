import config from 'config';
import { toGlobalId } from 'graphql-relay/node/node.js';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { PlatformIdentifier } from '../__generated__/resolvers-types';
import * as producer from '../thirdparty/pgboss/producer';
import {
  buildPendingUserActionLink,
  buildXtmPlatformTrialLink,
  clearTemplateCache,
  renderEmail,
  sendMail,
} from './mail-service';
import { formatProductNames, templateSubjects } from './mail-template/mail';

vi.mock('config', async (importOriginal) => {
  const mod = await importOriginal<{ default: typeof config }>();
  return {
    default: {
      get: vi.fn(mod.default.get.bind(mod.default)),
      has: mod.default.has.bind(mod.default),
    },
  };
});

const buildDigestUser = ({
  firstName,
  lastName,
  email,
}: {
  firstName: string;
  lastName: string;
  email: string;
}) => ({
  firstName,
  lastName,
  email,
  approveLink: `https://hub.test/redirect/handle-pending-user?action=approve&organization_id=orga-global-id&user_id=${email}-global-id`,
  denyLink: `https://hub.test/redirect/handle-pending-user?action=deny&organization_id=orga-global-id&user_id=${email}-global-id`,
});

describe('renderEmail', () => {
  afterEach(() => {
    clearTemplateCache();
  });

  describe('template loading', () => {
    it('should render a template file and return html', async () => {
      const html = await renderEmail('welcome', {});
      expect(html).toBeTruthy();
      expect(html).toContain('Welcome to XTM Hub');
    });

    it('should cache templates on subsequent calls', async () => {
      const html1 = await renderEmail('welcome', {});
      const html2 = await renderEmail('welcome', {});
      expect(html1).toBe(html2);
    });
  });

  describe('variable substitution', () => {
    it('should replace simple variables', async () => {
      const html = await renderEmail('new_user_organization', {
        organizationName: 'Filigran',
        userName: 'Alice',
        invitedName: 'Bob',
      });
      expect(html).toContain('Filigran');
      expect(html).toContain('Bob');
    });

    it('should inject base_url_front and contactEmail automatically', async () => {
      const html = await renderEmail('welcome', {});
      expect(html).not.toContain('{{ base_url_front }}');
      expect(html).not.toContain('{{ contactEmail }}');
      expect(html).toContain('xtm-hub-support@filigran.io');
    });

    it('should use template subject for title and aria-label', async () => {
      const params = {
        organizationName: 'Filigran',
        userName: 'Alice',
        invitedName: 'Bob',
      };
      const expectedTitle = templateSubjects.new_user_organization(params);
      const escapedExpectedTitle = expectedTitle.replaceAll("'", '&#x27;');

      const html = await renderEmail('new_user_organization', params);

      expect(html).toContain(`<title>${escapedExpectedTitle}</title>`);
      expect(html).toContain(`aria-label="${escapedExpectedTitle}"`);
    });
  });

  describe('hTML escaping', () => {
    it('should escape HTML in double-brace variables by default', async () => {
      const html = await renderEmail('new_user_organization', {
        organizationName: '<script>alert("xss")</script>',
        userName: 'Alice',
        invitedName: 'Bob',
      });
      expect(html).not.toContain('<script>alert("xss")</script>');
      expect(html).toContain('&lt;script&gt;');
    });
  });

  describe('{{#each}} loops', () => {
    it('should render a list of users in organization_pending_user_digest', async () => {
      const html = await renderEmail('organization_pending_user_digest', {
        adminName: 'Admin',
        adminEmail: 'admin@test.com',
        organizationName: 'Filigran',
        users: [
          buildDigestUser({
            firstName: 'John',
            lastName: 'Doe',
            email: 'john@test.com',
          }),
          buildDigestUser({
            firstName: 'Jane',
            lastName: 'Smith',
            email: 'jane@test.com',
          }),
        ],
        userCount: 2,
        requestLabel: 'requests',
      });
      expect(html).toContain('John');
      expect(html).toContain('Doe');
      expect(html).toContain('john@test.com');
      expect(html).toContain('Jane');
      expect(html).toContain('Smith');
      expect(html).toContain('jane@test.com');
      // Should have one action row per user generated by the {{#each}} loop
      expect(html.match(/>\s*Approve\s*</g)).toHaveLength(2);
    });

    it('should render an empty list when users array is empty', async () => {
      const html = await renderEmail('organization_pending_user_digest', {
        adminName: 'Admin',
        adminEmail: 'admin@test.com',
        organizationName: 'Filigran',
        users: [],
        userCount: 0,
        requestLabel: 'requests',
      });
      expect(html).toContain('Admin');
      expect(html).not.toContain('Approve');
    });

    it('should render a single user correctly', async () => {
      const html = await renderEmail('organization_pending_user_digest', {
        adminName: 'Admin',
        adminEmail: 'admin@test.com',
        organizationName: 'Filigran',
        users: [
          buildDigestUser({
            firstName: 'Solo',
            lastName: 'User',
            email: 'solo@test.com',
          }),
        ],
        userCount: 1,
        requestLabel: 'request',
      });
      const actionRowCount = (html.match(/>\s*Approve\s*</g) || []).length;
      expect(actionRowCount).toBe(1);
      expect(html).toContain('Solo');
      expect(html).toContain('solo@test.com');
    });
  });

  describe('{{#if}} tests', () => {
    it('should render text conditionally for free trials', async () => {
      const html = await renderEmail('free_trial_registered', {
        firstName: 'User',
        platformUrl: 'http://myTestPlatform',
        platformIdentifier: PlatformIdentifier.Openaev,
        globalServiceInstanceId: 'test-global-service-instance-id',
      });

      expect(html).not.toContain('OpenCTI');
    });
    it('should render text conditionally for free trials admin mail', async () => {
      const html = await renderEmail('admin_saas_instance_requested', {
        organizationName: 'myorga',
        userName: 'firstName lastName',
        userEmail: 'user.email',
        region: 'Test region',
        activitySector: 'Test ActivitySector',
        useCase: 'Test UseCase',
        platformIdentifier: PlatformIdentifier.Openaev,
        deploymentType: 'Trial',
      });

      expect(html).toContain('openaev-trials');
    });
  });

  describe('bundle free trials', () => {
    const bundleProductNames = 'OpenCTI, OpenAEV, and XTM One';

    const bundleProducts = [
      PlatformIdentifier.Opencti,
      PlatformIdentifier.Openaev,
      PlatformIdentifier.Xtmone,
    ];

    it.each([
      'free_trial_bundle_requested',
      'free_trial_bundle_provisioning',
      'free_trial_bundle_cancelled',
      'free_trial_bundle_expired',
    ] as const)(
      'should render %s without leaking undefined',
      async (template) => {
        const html = await renderEmail(template, {
          firstName: 'User',
          productNames: bundleProductNames,
          products: bundleProducts,
        });

        expect(html).toContain('XTM Platform');
        expect(html).not.toContain('undefined');
      }
    );

    it('should render the request wording', async () => {
      const html = await renderEmail('free_trial_bundle_requested', {
        firstName: 'User',
        productNames: bundleProductNames,
        products: bundleProducts,
      });

      expect(html.replace(/\s+/g, ' ')).toContain(
        'Thank you for requesting an <strong>XTM Platform Free Trial</strong>, we’re on it!'
      );
      expect(html).toContain(bundleProductNames);
      expect(html).not.toContain('full capacity');
    });

    it('should render the cancellation wording, the chosen products and the community link', async () => {
      const html = await renderEmail('free_trial_bundle_cancelled', {
        firstName: 'User',
        productNames: 'OpenCTI and XTM One',
        products: [PlatformIdentifier.Opencti, PlatformIdentifier.Xtmone],
      });

      expect(html.replace(/\s+/g, ' ')).toContain(
        'If you have any questions or need support, don’t hesitate to contact us at'
      );
      expect(html).toContain(
        'https://filigran-community.slack.com/archives/CHNEM9NUT'
      );
      expect(html).toContain('OpenCTI and XTM One');
      expect(html).not.toContain('OpenAEV');
    });

    it('should render the expiration wording', async () => {
      const html = await renderEmail('free_trial_bundle_expired', {
        firstName: 'User',
        productNames: bundleProductNames,
        products: bundleProducts,
      });

      expect(html).toContain('Your XTM Platform Trial has expired.');
      expect(html).toContain(
        '(Please note that your free trial data will only be saved for 7 days.)'
      );
    });

    it('should render the registered mail with the trial page link', async () => {
      const html = await renderEmail('free_trial_bundle_active', {
        firstName: 'User',
        platformUrl: 'http://myTestPlatform',
        productNames: bundleProductNames,
        products: bundleProducts,
      });

      expect(html).toContain('Your XTM Platform Trial is ready');
      expect(html).toContain(bundleProductNames);
      expect(html).toContain('http://myTestPlatform');
      expect(html).not.toContain('undefined');
    });

    it('should only describe the products of the bundle', async () => {
      const html = await renderEmail('free_trial_bundle_active', {
        firstName: 'User',
        platformUrl: 'http://myTestPlatform',
        productNames: 'OpenCTI and XTM One',
        products: [PlatformIdentifier.Opencti, PlatformIdentifier.Xtmone],
      });

      expect(html).toContain('to gather, enrich, analyze, and prioritize');
      expect(html).toContain('to add an agentic layer');
      expect(html).not.toContain('to simulate real-life attack scenarios');
    });
  });

  describe('product free trials', () => {
    it('should keep the support wording of the cancellation mail', async () => {
      const html = await renderEmail('free_trial_cancelled', {
        firstName: 'User',
        platformIdentifier: PlatformIdentifier.Opencti,
      });

      expect(html.replace(/\s+/g, ' ')).toContain(
        'If you have any questions or require support, don’t hesitate to reach out at'
      );
    });

    it('should keep the trial data retention wording of the expiration mail', async () => {
      const html = await renderEmail('free_trial_expired', {
        firstName: 'User',
        platformIdentifier: PlatformIdentifier.Opencti,
      });

      expect(html).toContain(
        '(Please note that your free trial data will be saved for 7 days.)'
      );
    });

    it('should keep the capacity wording of the queued mail', async () => {
      const html = await renderEmail('free_trial_queued', {
        firstName: 'User',
        platformIdentifier: PlatformIdentifier.Opencti,
      });

      expect(html).toContain('full capacity');
      expect(html).not.toContain('XTM Platform Free Trial');
    });
  });
  describe('edge cases', () => {
    it('should handle empty string values gracefully', async () => {
      const html = await renderEmail('organization_pending_user_digest', {
        adminName: 'Admin',
        adminEmail: 'admin@test.com',
        organizationName: 'Filigran',
        users: [
          buildDigestUser({
            firstName: '',
            lastName: 'Smith',
            email: 'user@test.com',
          }),
        ],
        userCount: 1,
        requestLabel: 'request',
      });
      expect(html).toContain('Smith');
      expect(html).toContain('user@test.com');
    });

    it('should escape special characters in user data within {{#each}}', async () => {
      const html = await renderEmail('organization_pending_user_digest', {
        adminName: 'Admin',
        adminEmail: 'admin@test.com',
        organizationName: 'Filigran',
        users: [
          buildDigestUser({
            firstName: '<b>Bold</b>',
            lastName: 'User',
            email: 'bold@test.com',
          }),
        ],
        userCount: 1,
        requestLabel: 'request',
      });
      expect(html).not.toContain('<b>Bold</b>');
      expect(html).toContain('&lt;b&gt;Bold&lt;/b&gt;');
    });

    it('should handle many users in the list', async () => {
      const users = Array.from({ length: 50 }, (_, i) =>
        buildDigestUser({
          firstName: `First${i}`,
          lastName: `Last${i}`,
          email: `user${i}@test.com`,
        })
      );
      const html = await renderEmail('organization_pending_user_digest', {
        adminName: 'Admin',
        adminEmail: 'admin@test.com',
        organizationName: 'Filigran',
        users,
        userCount: 50,
        requestLabel: 'requests',
      });
      const actionRowCount = (html.match(/>\s*Approve\s*</g) || []).length;
      expect(actionRowCount).toBe(50);
      expect(html).toContain('First0');
      expect(html).toContain('First49');
    });
  });

  describe('pending user action links', () => {
    const organizationId = '11111111-1111-1111-1111-111111111111';
    const userId = '22222222-2222-2222-2222-222222222222';

    const buildLinks = () => ({
      approveLink: buildPendingUserActionLink({
        action: 'approve',
        organizationId,
        userId,
      }),
      denyLink: buildPendingUserActionLink({
        action: 'deny',
        organizationId,
        userId,
      }),
    });

    it.each`
      action       | typeName          | rawId
      ${'approve'} | ${'Organization'} | ${organizationId}
      ${'approve'} | ${'User'}         | ${userId}
      ${'deny'}    | ${'Organization'} | ${organizationId}
      ${'deny'}    | ${'User'}         | ${userId}
    `(
      'should encode the $typeName id as a global id for action "$action"',
      ({ action, typeName, rawId }) => {
        const link = buildPendingUserActionLink({
          action,
          organizationId,
          userId,
        });

        const searchParams = new URL(link).searchParams;
        const param =
          typeName === 'Organization' ? 'organization_id' : 'user_id';

        expect(searchParams.get('action')).toBe(action);
        expect(searchParams.get(param)).toBe(toGlobalId(typeName, rawId));
      }
    );

    it('should point to the handle-pending-user redirect route', () => {
      const { approveLink } = buildLinks();

      expect(new URL(approveLink).pathname).toBe(
        '/redirect/handle-pending-user'
      );
    });

    it('should percent-encode the base64 padding of global ids', () => {
      const { approveLink } = buildLinks();

      expect(approveLink).not.toContain('=&');
      expect(approveLink).toContain('%3D');
    });

    it('should only differ by the action query param between approve and deny', () => {
      const { approveLink, denyLink } = buildLinks();

      expect(approveLink.replace('action=approve', 'action=deny')).toBe(
        denyLink
      );
    });

    it('should render one action row per pending user with its own links', async () => {
      const users = [
        { firstName: 'John', lastName: 'Doe', email: 'john@test.com' },
        { firstName: 'Jane', lastName: 'Smith', email: 'jane@test.com' },
        { firstName: 'Jack', lastName: 'Brown', email: 'jack@test.com' },
      ].map((user, index) => ({
        ...user,
        approveLink: buildPendingUserActionLink({
          action: 'approve',
          organizationId,
          userId: `${index}-${userId}`,
        }),
        denyLink: buildPendingUserActionLink({
          action: 'deny',
          organizationId,
          userId: `${index}-${userId}`,
        }),
      }));

      const html = await renderEmail('organization_pending_user_digest', {
        adminName: 'Admin',
        adminEmail: 'admin@test.com',
        organizationName: 'Filigran',
        users,
        userCount: users.length,
        requestLabel: 'requests',
      });

      // Handlebars HTML-escapes `&` and `=` within the double-stash query
      // string (e.g. `action=approve` becomes `action&#x3D;approve`), so
      // decode entities before comparing against the raw links.
      const decodedHtml = html.replace(/&amp;/g, '&').replace(/&#x3D;/g, '=');

      expect(decodedHtml.match(/action=approve/g)).toHaveLength(users.length);
      expect(decodedHtml.match(/action=deny/g)).toHaveLength(users.length);
      expect(html.match(/>\s*Approve\s*</g)).toHaveLength(users.length);
      expect(html.match(/>\s*Deny\s*</g)).toHaveLength(users.length);

      users.forEach((user) => {
        expect(decodedHtml).toContain(`href="${user.approveLink}"`);
        expect(decodedHtml).toContain(`href="${user.denyLink}"`);
      });
    });

    it('should not render any action row when there is no pending user', async () => {
      const html = await renderEmail('organization_pending_user_digest', {
        adminName: 'Admin',
        adminEmail: 'admin@test.com',
        organizationName: 'Filigran',
        users: [],
        userCount: 0,
        requestLabel: 'requests',
      });

      expect(html).not.toContain('handle-pending-user');
      expect(html).not.toContain('Approve');
    });
  });

  describe('sendMail', () => {
    it('should enqueue a job via PgBossProducer when queue processing is enabled', async () => {
      vi.mocked(config.get).mockReturnValue(true);

      const mockSend = vi
        .spyOn(producer.PgBossProducer, 'send')
        .mockResolvedValue('fake-job-id');

      await sendMail({
        to: 'test@example.com',
        template: 'welcome',
        params: {},
      });

      expect(mockSend).toHaveBeenCalledOnce();
      expect(mockSend).toHaveBeenCalledWith('mail.send', {
        to: 'test@example.com',
        template: 'welcome',
        params: {},
      });
    });

    it('should NOT enqueue a job when queue processing is disabled', async () => {
      vi.mocked(config.get).mockReturnValue(false);

      const mockSend = vi
        .spyOn(producer.PgBossProducer, 'send')
        .mockResolvedValue('fake-job-id');

      await sendMail({
        to: 'test@example.com',
        template: 'welcome',
        params: {},
      });

      expect(mockSend).not.toHaveBeenCalled();
    });
  });
});

describe('formatProductNames', () => {
  it('should format a single product', () => {
    expect(formatProductNames([PlatformIdentifier.Opencti])).toBe('OpenCTI');
  });

  it('should format two products', () => {
    expect(
      formatProductNames([
        PlatformIdentifier.Opencti,
        PlatformIdentifier.Xtmone,
      ])
    ).toBe('OpenCTI and XTM One');
  });

  it('should format three products', () => {
    expect(
      formatProductNames([
        PlatformIdentifier.Opencti,
        PlatformIdentifier.Openaev,
        PlatformIdentifier.Xtmone,
      ])
    ).toBe('OpenCTI, OpenAEV, and XTM One');
  });

  it('should return an empty string without product', () => {
    expect(formatProductNames([])).toBe('');
  });
});

describe('bundle trial subjects', () => {
  it('should use the XTM Platform wording for bundles', () => {
    const params = {
      firstName: 'User',
      productNames: 'OpenCTI and XTM One',
      products: [PlatformIdentifier.Opencti, PlatformIdentifier.Xtmone],
    };

    expect(templateSubjects.free_trial_bundle_requested(params)).toBe(
      'Your XTM Platform Trial Request'
    );
    expect(templateSubjects.free_trial_bundle_provisioning(params)).toBe(
      'Your XTM Platform Trial is Being Provisioned'
    );
    expect(
      templateSubjects.free_trial_bundle_active({
        ...params,
        platformUrl: 'http://myTestPlatform',
      })
    ).toBe('Your XTM Platform Trial is ready');
    expect(templateSubjects.free_trial_bundle_cancelled(params)).toBe(
      'Your XTM Platform Trial Has Been Cancelled'
    );
    expect(templateSubjects.free_trial_bundle_expired(params)).toBe(
      'Your XTM Platform Trial Has Expired'
    );
  });

  it('should keep the product wording outside of bundles', () => {
    const params = {
      firstName: 'User',
      platformIdentifier: PlatformIdentifier.Opencti,
    };

    expect(templateSubjects.free_trial_requested(params)).toBe(
      'Your OpenCTI Free Trial Request'
    );
    expect(templateSubjects.free_trial_expired(params)).toBe(
      'Your OpenCTI Free Trial Has Expired'
    );
  });
});

